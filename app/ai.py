def _key(text):
    return "".join(text.split()).lower()


# 일부만 같아도 찾아 주면 "깨진 유리병"에 "유리병" 답이 나올 수 있어서, 이름이 똑같을 때만 찾는다.
_BY_NAME = {_key(word): guide for guide in GUIDES for word in [guide["name"], *guide["aliases"]]}


def guide_by_name(name):
    """이름으로 분리배출 방법을 찾는다. 없으면 None."""
    guide = _BY_NAME.get(_key(name))
    if guide is None:
        return None
    return {
        "name": guide["name"],
        "category": guide["category"],
        "steps": guide["steps"],
        "source": SOURCE,
    }


def _name_from_photo(image):
    # 연습용 가짜 답. 사진을 보지 않고 늘 같은 이름을 준다. AI 키가 생기면 이 함수를 진짜로 바꾼다.
    return "투명 페트병"


def guide_by_photo(image):
    """사진(bytes)으로 분리배출 방법을 찾는다. 없으면 None. fake가 True면 가짜 답이다."""
    guide = guide_by_name(_name_from_photo(image))
    if guide is None:
        return None
    return {**guide, "fake": True}
